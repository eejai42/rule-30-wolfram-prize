"""The ledger in Lean: write lean/Rule30Ledger.lean from the compiled rulebook, check it against the kit.

For every claim the build can write in Lean (Assertions.LeanStatement, from its term tree) the file has one
theorem, with its proof from LeanProofs or `sorry`; for a claim with an alignment proof it also states
that our statement is equivalent to the official constant. Then:

  pass 1  every proof replaced by `sorry`: a theorem that fails here has a statement Lean rejects
          (elaborates = 0) and is left out of the next passes;
  pass 2  the real proofs: a proof that fails is replaced by `sorry` and its error recorded;
  check   the kit's own Check.lean (kernel replay, standard axioms only) on every theorem.

The verdicts go to research/lean/checks.json and from there into LeanChecks, which the formulas read.
Nothing here sets a status. refresh() is called by loop_tools.build() after the first compile, and does
nothing when neither the Lean file nor the kit commit changed since the last check.

Usage: python3 research/lean/ledger.py [--force]   (check now if stale, or always with --force; load the verdicts)
"""
from __future__ import annotations
import hashlib, json, re, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / 'research'))
sys.path.insert(0, str(ROOT / 'research' / 'hub'))
sys.path.insert(0, str(HERE))
import leankit as lk

LEAN_FILE = ROOT / 'lean' / 'Rule30Ledger.lean'
CHECKS = HERE / 'checks.json'
MODULE = 'Rule30Ledger'

PRELUDE = '''import Rule30PrizeKit
import Ruliology
import Mathlib.Dynamics.PeriodicPts.Defs

/-!
# The Rule 30 research ledger, in Lean

GENERATED by research/lean/ledger.py from the compiled rulebook. Do not edit: change a claim's term tree
(research/hub/build_model.py, formal_claims.py) or its proof (research/lean/proofs.py) and build.

Every theorem `claim_<id>` states one ledger claim, written by the build from the claim's term tree
(Assertions.LeanStatement). A theorem proved by `sorry` is an open Lean obligation: the kit's Check.lean
rejects it, so the claim does not count as Lean-verified. `official_<id>` states that a prize problem's
formal statement here is equivalent to the official one in the kit.

The vocabulary below gives the model's operators their meaning in terms of the kit's `cell`, `R` and `D`.
-/

namespace Rule30Ledger

open Ruliology.CellularAutomata

/-- A cell as the model holds it: 1 for black, 0 for white. -/
def bit (b : Bool) : Nat := if b then 1 else 0

/-- x(i, t): the cell at position i after t steps. -/
def x (i : Int) (t : Nat) : Nat := bit (Rule30Jen.cell t i)

/-- c(t): the center column. -/
def c (t : Nat) : Nat := bit (Rule30Prize.center t)

/-- y_k(t) = x(t - k, t): the k-th diagonal from the right edge (the kit's R). -/
def y (k t : Nat) : Nat := bit (Rule30Diagonals.R k t)

/-- w_k(t) = x(k - t, t): the k-th diagonal from the left edge (the kit's D). -/
def w (k t : Nat) : Nat := bit (Rule30Diagonals.D k t)

/-- Rule 30 on 0/1 cells: l XOR (q OR r). -/
def rule30 (l q r : Nat) : Nat := bit (Rule30Jen.rule (l == 1) (q == 1) (r == 1))

def Power (a b : Nat) : Nat := a ^ b
def Mod (a b : Nat) : Nat := a % b
def bxor (a b : Nat) : Nat := bit ((a == 1) ^^ (b == 1))
def bor (a b : Nat) : Nat := bit ((a == 1) || (b == 1))

/-- The time shift on sequences. -/
def shift (f : Nat → Nat) : Nat → Nat := fun t => f (t + 1)

/-- P k: the least period of the right diagonal y_k. -/
noncomputable def P (k : Nat) : Nat := Function.minimalPeriod shift (y k)

/-- Eps k: 1 when the least period doubles at k. -/
noncomputable def Eps (k : Nat) : Nat := if P k = 2 * P (k - 1) then 1 else 0

theorem bit_inj {a b : Bool} : bit a = bit b ↔ a = b := by cases a <;> cases b <;> simp [bit]
theorem bit_eq_one {a : Bool} : bit a = 1 ↔ a = true := by cases a <;> simp [bit]
theorem bit_eq_zero {a : Bool} : bit a = 0 ↔ a = false := by cases a <;> simp [bit]
theorem bit_beq_one (a : Bool) : (bit a == 1) = a := by cases a <;> rfl

theorem iterate_shift (f : Nat → Nat) (n : Nat) : shift^[n] f = fun t => f (t + n) := by
  induction n generalizing f with
  | zero => rfl
  | succ n ih =>
    rw [Function.iterate_succ_apply, ih]
    funext t
    simp only [shift]
    congr 1
    all_goals omega
'''


def theorem_name(kind: str, aid: str) -> str:
    return ('official_' if kind == 'alignment' else 'claim_') + re.sub(r'[^A-Za-z0-9_]', '_', aid)


def items(book: dict) -> list[dict]:
    """One item per theorem: the claim, its statement, its proof (or None)."""
    proofs = {(p['Assertion'], p['Kind']): p for p in book['LeanProofs']['data']}
    out = []
    for a in book['Assertions']['data']:
        st = a.get('LeanStatement') or ''
        if not st:
            continue
        p = proofs.get((a['AssertionId'], 'claim'))
        out.append({'claim': a['AssertionId'], 'kind': 'claim', 'theorem': theorem_name('claim', a['AssertionId']), 'statement': st,
                    'type': st, 'proof': p['Proof'] if p else None, 'target': ''})
        al = proofs.get((a['AssertionId'], 'alignment'))
        if al:
            out.append({'claim': a['AssertionId'], 'kind': 'alignment', 'theorem': theorem_name('alignment', a['AssertionId']), 'statement': st,
                        'type': f"{st} ↔ {al['Target']}", 'proof': al['Proof'], 'target': al['Target']})
    return out


def render(its: list[dict], use_proofs: bool) -> tuple[str, dict]:
    """The Lean file, and for each theorem the line range it occupies."""
    lines = PRELUDE.rstrip('\n').split('\n') + ['']
    spans = {}
    for it in its:
        start = len(lines) + 1
        proof = it['proof'] if (use_proofs and it['proof']) else 'by\n  sorry'
        lines.append(f"/-- {it['claim']}{' (alignment with ' + it['target'] + ')' if it['target'] else ''}. -/")
        lines.append(f"theorem {it['theorem']} : {it['type']} :=")
        lines += ['  ' + ln if ln else ln for ln in proof.split('\n')]
        lines.append('')
        spans[it['theorem']] = (start, len(lines))
    lines.append('end Rule30Ledger')
    return '\n'.join(lines) + '\n', spans


def errors_by_theorem(messages: str, spans: dict) -> dict:
    out = {}
    for m in re.finditer(r'Rule30Ledger\.lean:(\d+):\d+: error[^:]*: (.*?)(?=\n\S+\.lean:\d+:\d+: |\Z)', messages, re.S):
        line = int(m.group(1))
        for name, (a, b) in spans.items():
            if a <= line <= b:
                out.setdefault(name, []).append(' '.join(m.group(2).split())[:600])
    return out


def run(book: dict) -> dict:
    its = items(book)
    work = lk.OUT / 'ledger'
    src = work / 'Rule30Ledger.lean'
    work.mkdir(parents=True, exist_ok=True)
    # pass 1: statements only
    text, spans = render(its, use_proofs=False)
    src.write_text(text)
    ok, msgs = lk.compile_module(src, MODULE, work)
    bad_statements = errors_by_theorem(msgs, spans) if not ok else {}
    if not ok and not bad_statements:
        raise RuntimeError(f'the Lean prelude does not compile:\n{msgs[-3000:]}')
    good = [it for it in its if it['theorem'] not in bad_statements]
    # pass 2: real proofs; a failing proof falls back to sorry
    failed_proofs: dict = {}
    for _ in range(3):
        with_proofs = [dict(it, proof=None) if it['theorem'] in failed_proofs else it for it in good]
        text, spans = render(with_proofs, use_proofs=True)
        src.write_text(text)
        ok, msgs = lk.compile_module(src, MODULE, work)
        if ok:
            break
        errs = errors_by_theorem(msgs, spans)
        if not errs:
            raise RuntimeError(f'Rule30Ledger.lean failed outside any theorem:\n{msgs[-3000:]}')
        failed_proofs.update(errs)
    else:
        raise RuntimeError(f'Rule30Ledger.lean still fails after replacing failing proofs:\n{msgs[-3000:]}')
    LEAN_FILE.write_text(text)
    result = lk.check(MODULE, [f'Rule30Ledger.{it["theorem"]}' for it in good], work)
    by_name = {h['name'].removeprefix('Rule30Ledger.'): h for h in result.get('headlines', [])}
    checks = []
    for it in its:
        name = it['theorem']
        h = by_name.get(name, {})
        problems = [f'statement: {e}' for e in bad_statements.get(name, [])] + [f'proof: {e}' for e in failed_proofs.get(name, [])]
        if not it['proof'] and name not in bad_statements:
            problems.append('no proof yet (sorry)')
        problems += [p for p in h.get('problems', []) if 'sorryAx' not in p or it['proof']]
        checks.append({'claim': it['claim'], 'kind': it['kind'], 'theorem': name, 'statement': it['statement'], 'target': it['target'],
                       'elaborates': name not in bad_statements, 'has_proof': bool(it['proof']) and name not in failed_proofs and name not in bad_statements,
                       'ok': bool(h.get('ok')), 'axioms': h.get('axioms', []), 'problems': problems})
    kit = json.loads((ROOT / 'research' / 'sources' / 'snapshots' / 'kit.json').read_text())
    out = {'kitCommit': kit['commit'], 'checkedAt': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
           'leanFileSha256': hashlib.sha256(text.encode()).hexdigest(), 'inputSha256': input_hash(its, kit['commit']),
           'replay': result.get('replay'), 'verdict': result.get('verdict'), 'checks': checks}
    CHECKS.write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n')
    return out


def input_hash(its: list[dict], commit: str) -> str:
    return hashlib.sha256(json.dumps([commit, PRELUDE, its], sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def is_current(book: dict) -> bool:
    if not CHECKS.exists():
        return False
    kit = json.loads((ROOT / 'research' / 'sources' / 'snapshots' / 'kit.json').read_text())
    return json.loads(CHECKS.read_text()).get('inputSha256') == input_hash(items(book), kit['commit'])


def refresh(book: dict) -> str:
    """Called by loop_tools.build() on a freshly compiled rulebook. Returns a receipt line."""
    if 'LeanProofs' not in book:
        return 'lean: no challenge tables yet'
    if is_current(book):
        return 'lean: current'
    if not lk.available():
        return 'lean: skipped (no Lean toolchain or kit checkout; see CLAUDE.md, Lean)'
    out = run(book)
    import build_challenge
    build_challenge.load_lean_checks(book, out)
    n_ok = sum(1 for c in out['checks'] if c['ok'])
    return f"lean: {n_ok} of {len(out['checks'])} theorems verified ({out['verdict']})"


if __name__ == '__main__':
    import loop_tools as lt
    b = lt.load()
    if '--force' in sys.argv and CHECKS.exists():
        CHECKS.unlink()
    print(refresh(b))
    lt.save(b)
    print('LeanChecks saved; run python3 research/build.py to compile them in.')
